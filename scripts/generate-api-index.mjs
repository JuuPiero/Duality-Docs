import { readdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'

const docsRoot = process.cwd()
const engineRoot = path.resolve(process.env.DUALITY_ENGINE_ROOT ?? path.join(docsRoot, '..', '..', 'CPP', 'DualityEngine'))
const includeRoot = path.join(engineRoot, 'DualityEngine', 'Include', 'DualityEngine')
const output = path.join(docsRoot, 'src', 'data', 'generatedHeaders.ts')

async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const results = []
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name)
    if (entry.isDirectory()) results.push(...await collect(fullPath))
    else if (entry.name.endsWith('.h')) results.push(fullPath)
  }
  return results
}

function symbolsFrom(text) {
  const symbols = new Set()
  for (const match of text.matchAll(/^\s*(?:class|struct|enum class)\s+([A-Za-z_]\w*)/gm)) symbols.add(match[1])
  // Public headers in Duality intentionally contain many small inline wrappers. Index both
  // declarations ending in ';' and inline declarations beginning a body, but only keep their
  // signature (never header implementation text). This stays a discovery index, not a C++ parser.
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line.includes('(') || line.startsWith('//') || /^(if|for|while|switch|return)\b/.test(line)) continue
    const match = line.match(/^(?:(?:virtual|static|inline|explicit)\s+)?(?:[\w:<>~]+\s*[*&]?\s+)+[A-Za-z_~]\w*\s*\([^;{}]*\)\s*(?:const)?\s*(?:override)?\s*(?:=\s*0)?\s*(?:[;{]|$)/)
    if (match) symbols.add(match[0].replace(/[;{]\s*$/, '').trim())
  }
  return [...symbols].slice(0, 80)
}

if (!existsSync(includeRoot)) {
  throw new Error(`Duality include root was not found: ${includeRoot}. Set DUALITY_ENGINE_ROOT to the engine repository root.`)
}

const files = await collect(includeRoot)
const catalogue = []
for (const file of files.sort()) {
  const content = await readFile(file, 'utf8')
  catalogue.push({ path: path.relative(engineRoot, file).replaceAll('\\', '/'), symbols: symbolsFrom(content) })
}

const source = `// Generated by scripts/generate-api-index.mjs. Do not edit by hand.\nexport type HeaderCatalogueItem = { path: string; symbols: string[] }\nexport const headerCatalogue: HeaderCatalogueItem[] = ${JSON.stringify(catalogue, null, 2)}\n`
await writeFile(output, source)
console.log(`Indexed ${catalogue.length} public engine headers.`)
